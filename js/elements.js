/* 分類 */
const NONMETALS  = [1,6,7,8,9,15,16,17,34,35,53,85];
const NOBLE_GASES = [2,10,18,36,54,86];
const METALLOIDS = [5,14,32,33,51,52];

function computeType(no) {
  // 104番以上は性質がはっきりしていないので分類しない
  if (no >= 104) return null;
  if (NOBLE_GASES.includes(no)) return '貴ガス';
  if (METALLOIDS.includes(no)) return '半金属';
  if (NONMETALS.includes(no))  return '非金属';
  return '金属';
}

/* 常温での状態 */
const GASES   = [1,2,7,8,9,10,17,18,36,54,86];
const LIQUIDS = [35,80];

function computeState(no) {
  // 101番以上はごくわずかしかつくれず、状態がはっきりしていない
  if (no >= 101) return null;
  if (GASES.includes(no))   return '気体';
  if (LIQUIDS.includes(no)) return '液体';
  return '固体';
}

/* 周期表の位置 [row, col] */
function computePosition(no) {
  if (no === 1)  return [1, 1];
  if (no === 2)  return [1, 18];
  if (no <= 10)  return [2, no <= 4 ? no - 2 : no + 8];
  if (no <= 18)  return [3, no <= 12 ? no - 10 : no];
  if (no <= 36)  return [4, no - 18];
  if (no <= 54)  return [5, no - 36];
  if (no <= 56)  return [6, no - 54];
  if (no === 57) return [6, 3];
  if (no <= 71)  return [9, no - 54];   // ランタノイド（58〜71）
  if (no <= 86)  return [6, no - 68];
  if (no <= 88)  return [7, no - 86];
  if (no === 89) return [7, 3];
  if (no <= 103) return [10, no - 86];  // アクチノイド（90〜103）
  return [7, no - 100];
}

/* 族 */
function computeGroup(no) {
  if (no >= 57 && no <= 71) return 'ランタノイド';
  if (no >= 89 && no <= 103) return 'アクチノイド';
  return computePosition(no)[1] + '族';
}

const ELEMENTS = ELEMENT_NAMES.map(([no, sym, name]) => {
  const [row, col] = computePosition(no);
  return {
    no, sym, name, row, col,
    type:  computeType(no),
    state: computeState(no),
    group: computeGroup(no),
    note:  ELEMENT_NOTES[no],
  };
});
